export type LynxIconName = keyof typeof ICONS;

interface LynxIconProps extends Omit<React.SVGAttributes<SVGSVGElement>, 'children' | 'name'> {
  name: LynxIconName;
  filled?: boolean;
  size?: 16 | 20 | 24 | 40 | 48;
  label?: string;
  spin?: boolean;
}

/** Central Fluent UI System Icons entry point for product UI. */
export const LynxIcon: React.FC<LynxIconProps> = ({
  name,
  filled = false,
  size = 20,
  label,
  spin = false,
  className = '',
  ...svgProps
}) => {
  const Icon = ICONS[name][filled ? 1 : 0];
  return (
    <Icon
      {...svgProps}
      className={`lynx-icon${spin ? ' lynx-icon--spin' : ''} ${className}`.trim()}
      width={size}
      height={size}
      aria-hidden={label ? undefined : true}
      aria-label={label}
      role={label ? 'img' : undefined}
    />
  );
};

export default LynxIcon;
